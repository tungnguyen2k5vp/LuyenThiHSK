    visualType: "none",
    imageUri: null,
    imageSource: null,
    imageLicense: null,
    imageAttribution: null,
    audioUri: null,
    source: "HanZi curated Vietnamese names",
    sourceVersion: "2026-09-18",
    sourceUrl: "local://supplemental-names",
