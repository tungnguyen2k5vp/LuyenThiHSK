import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createHash } from 'node:crypto';
import { emptyLearning, parseLearning, initialProgress, createSession, finishLearningWord, gradeReview, reviewQueue, learningStats, answerOptions } from '../src/chinese/learning.ts';
import { calculateStreak, toLocalDateKey } from '../src/chinese/reused/calendar.ts';

const words = JSON.parse(fs.readFileSync(new URL('../public/data/fourchinese/words.json', import.meta.url), 'utf8'));
const manifest = JSON.parse(fs.readFileSync(new URL('../public/data/fourchinese/manifest.json', import.meta.url), 'utf8'));
assert.equal(words.length, manifest.totalWords);
assert.equal(new Set(words.map(word => word.id)).size, words.length);
assert(words.length > 11828, 'Keep the app starter and supplemental additions');
assert(words.every(word => word.audioExamples.every(example => example.audioUrl.startsWith('/data/open-hsk/audio/'))));
assert(words.every(word => word.syllabusLevels.every(level => ['1', '2', '3', '4', '5', '6', '7-9'].includes(level))));
assert.equal(words.filter(word => word.audioExamples.length).length, manifest.withAudioExamples);
const source = new URL('../../HocTiengTrungApp/src/data/hsk-vocabulary.json', import.meta.url);
if (fs.existsSync(source)) assert.equal(createHash('sha256').update(fs.readFileSync(source)).digest('hex'), manifest.sourceSha256, 'The source app dictionary must remain untouched');

const now = new Date(2026, 10, 8, 9, 0), [word, other, third] = words;
let data = finishLearningWord(emptyLearning(), word.id, now);
assert.equal(learningStats(data, now).learned, 1);
assert.equal(learningStats(data, now).newToday, 1);
assert.equal(reviewQueue(words, data, now).length, 0, 'New cards wait thirty minutes');
assert.throws(() => finishLearningWord(data, word.id, now), /đổi trạng thái/);
data.progress[other.id] = initialProgress('KNOWN', now);
data.progress[third.id] = initialProgress('SKIPPED', now);
const later = new Date(now.getTime() + 31 * 60000);
assert.deepEqual(reviewQueue(words, data, later).map(item => item.id), [word.id], 'Known and skipped words never enter the due queue');
data.session = createSession('review', [word.id], 'hanzi-meaning');
assert.throws(() => gradeReview(data, other.id, true, 'hanzi-meaning', 6000, false, later), /hiện tại/);
data = gradeReview(data, word.id, false, 'hanzi-meaning', 6000, false, later);
assert.equal(data.progress[word.id].reviewCount, 1);
assert.equal(data.events.filter(event => event.kind === 'review').length, 1);
assert.equal(data.session.ids.length, 2, 'A wrong answer gets one retry');
assert.throws(() => gradeReview(data, word.id, true, 'hanzi-meaning', 6000, false, later), /đã được lưu/);
const savedDue = data.progress[word.id].nextReviewAt;
data = parseLearning(JSON.parse(JSON.stringify(data)));
assert.equal(data.session.feedback.correct, false, 'Reload must preserve feedback and prevent double grading');
data.session = { ...data.session, index: 1, feedback: null };
data = gradeReview(data, word.id, true, 'hanzi-meaning', 6000, false, later);
assert.equal(data.progress[word.id].nextReviewAt, savedDue, 'In-session retries must not push the schedule twice');
assert.equal(data.progress[word.id].reviewCount, 1);
assert.equal(data.events.at(-1).kind, 'practice');
assert.equal(data.session.ids.length, 2, 'Do not requeue a card repeatedly');
data.session = createSession('practice', [word.id], 'hanzi-meaning');
data = gradeReview(data, word.id, true, 'hanzi-meaning', 1000, false, later);
assert.equal(data.progress[word.id].nextReviewAt, savedDue, 'Early practice must leave the schedule intact');
assert.equal(learningStats(data, later).reviewedToday, 1);
const hinted = finishLearningWord(emptyLearning(), word.id, now);
hinted.session = createSession('review', [word.id]);
const result = gradeReview(hinted, word.id, true, 'meaning-hanzi', 6000, true, later);
assert.equal(result.progress[word.id].memoryLevel, 1, 'A hint must not promote a card');
assert.throws(() => parseLearning({ ...data, progress: { [word.id]: { ...data.progress[word.id], memoryLevel: 100 } } }));
assert.throws(() => parseLearning({ ...data, settings: { ...data.settings, dailyGoal: -1 } }));
assert.throws(() => createSession('learn', [word.id, word.id]));
assert(answerOptions(word, words, 'simplified').includes(word.simplified));
assert.equal(new Set(answerOptions(word, words, 'primaryMeaningVi')).size, answerOptions(word, words, 'primaryMeaningVi').length);
const yesterday = new Date(now); yesterday.setDate(yesterday.getDate() - 1);
assert.equal(calculateStreak([toLocalDateKey(yesterday)], now), 1);
console.log('PASS: canonical dictionary, source checksum, three-stage completion boundary, due eligibility, single grading, persisted feedback, retry limit, practice isolation, hints, statistics and backup validation.');
