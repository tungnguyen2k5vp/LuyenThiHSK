// Run from LuyenThiHSK: node --import tsx scripts/test-hsk-portal.mjs
import assert from 'node:assert/strict';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { HskHome } from '../src/components/dashboard/HskHome.tsx';
import { PracticeHub } from '../src/components/preparation/LearningHubs.tsx';
import { HskSidebar, portalActivePage, PORTAL_NAV } from '../src/components/layout/HskNavigation.tsx';
import { readExamRoute, routeUrl } from '../src/services/examRoute.ts';
import { emptyPreparation, localDay, freshCourseCard } from '../src/services/preparationStorage.ts';
import { emptyStudyData } from '../src/services/studyStorage.ts';
import { QUESTION_BANKS, resolveExam } from '../src/data/examCatalog.ts';

const route = readExamRoute('?view=dashboard&version=hsk3');
assert.equal(readExamRoute(routeUrl({ ...route, page: 'plan' })).page, 'plan');
assert.equal(readExamRoute('?view=unknown').page, 'dashboard');
assert.equal(portalActivePage('parts'), 'practice');
assert.equal(portalActivePage('grammar'), 'learn');
assert.equal(portalActivePage('history'), 'progress');
for (const item of PORTAL_NAV) assert.equal(readExamRoute(routeUrl({ ...route, page: item.page })).page, item.page);
const sidebar = renderToStaticMarkup(createElement(HskSidebar, { route: { ...route, page: 'parts' }, onNavigate() {} }));
assert.equal((sidebar.match(/aria-current="page"/g) ?? []).length, 1);
assert.match(sidebar, /aria-label="Điều hướng chính"/);
assert.match(sidebar, /<summary/);

const preparation = emptyPreparation();
const study = emptyStudyData();
const render = () => renderToStaticMarkup(createElement(HskHome, { preparation, study, route, onNavigate() {} }));
const empty = render();
assert.match(empty, /Đang tải các cấp học/);
assert.match(empty, /Tạo kế hoạch để bắt đầu/);
assert.doesNotMatch(empty, /BÀI ĐANG LÀM/);
assert.match(empty, /section=listening/);
assert.match(empty, /section=reading/);
assert.match(empty, /view=writing/);
assert.match(empty, /view=speaking/);
assert.match(empty, /view=exams/);
assert.match(empty, /Học nền tảng · syllabus 2025/);
assert.match(empty, /Chưa có bài làm/);
assert.match(empty, /aria-pressed="true">HSK 1/);
assert.match(empty, /view=vocab[^\"]*level=HSK\+1/);
const level3 = renderToStaticMarkup(createElement(HskHome, { preparation, study, route:{...route,level:'HSK 3'}, onNavigate() {} }));
assert.match(level3, /aria-pressed="true">HSK 3/);
assert.match(level3, /view=vocab[^\"]*level=HSK\+3/);
assert.match(level3, /view=parts[^\"]*level=HSK\+3[^\"]*section=listening/);
const hub=renderToStaticMarkup(createElement(PracticeHub,{study,route:{...route,level:'HSK 3'},targetLevel:'1',onNavigate(){}}));
for(const title of ['Nghe hiểu','Đọc hiểu','Chép chính tả','Sắp xếp câu','Góc luyện viết','Góc luyện nói'])assert.match(hub,new RegExp(title));
assert.match(hub,/aria-pressed="true">HSK 3/);
assert.match(hub,/không quy đổi thành điểm thi HSK/);
assert.doesNotMatch(hub,/AI chấm/);

const bank = QUESTION_BANKS[0];
const now = new Date().toISOString();
study.sessions.push({ id: 'portal-resume', examId: bank.id, examSnapshot: bank, mode: 'practice', answers: {}, currentIndex: 2, checkedQuestionIds: [], flaggedQuestionIds: [], startedAt: now, updatedAt: now });
const before = JSON.stringify({ preparation, study });
const resumed = render();
assert.match(resumed, /Câu 3\/10/);
assert.match(resumed, /session=portal-resume/);
assert.equal(resolveExam(study.sessions[0]), bank);
assert.equal(JSON.stringify({ preparation, study }), before, 'Rendering must preserve existing study data');

preparation.cards.word = { ...freshCourseCard('word', '1'), learned: true, updatedAt: now };
preparation.events.push({ id: 'event', kind: 'word-learn', entityId: 'word', at: now, count: 1, minutes: 0 });
preparation.plans[localDay()] = { day: localDay(), createdAt: now, skipped: [], tasks: [{ id: 'words', title: 'Học từ', kind: 'word-learn', count: 1, minutes: 5, page: 'vocab' }] };
const completed = render();
assert.match(completed, /1\/1 nhiệm vụ hoàn thành/);
assert.match(completed, /<progress max="1" value="1"/);
assert.match(completed, /<strong>1<\/strong><span>Từ vựng đã học/);
assert.match(completed,/Học từ/);
assert.equal(preparation.profile.targetLevel, '1');
console.log('PASS portal: routes, active navigation, accessible mobile menu, empty data, skill links, session resume, real study progress, no data mutation.');
